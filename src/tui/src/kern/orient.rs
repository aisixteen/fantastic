//! The state folder's `readme.md`, rewritten from the live values at every boot.

use std::path::{Path, PathBuf};

use fantastic_kernel::AgentId;

use crate::kern::host::Host;

/// The folder of bridge `id` (where its file lives).
fn folder_of(h: &Host, id: &str) -> Option<PathBuf> {
    h.kernel.agents.get(&AgentId::from(id)).map(|a| a.value().root_path.clone())
}

/// `- <id> (<handler_module>) <display name>` for each child of `parent`, sorted.
fn children_of(h: &Host, parent: &str) -> Vec<String> {
    let Some(p) = h.kernel.agents.get(&AgentId::from(parent)).map(|a| a.value().clone()) else {
        return Vec::new();
    };
    let mut rows: Vec<String> = p
        .child_ids()
        .iter()
        .filter_map(|id| h.kernel.agents.get(id))
        .map(|a| {
            let a = a.value();
            let handler = a.handler_module.clone().unwrap_or_default();
            let name = a.display_name().unwrap_or_default();
            format!("- `{}` ({handler}) {name}", a.id.0)
        })
        .collect();
    rows.sort();
    rows
}

/// (Re)write `<state>/readme.md` from the live values, atomically, on every boot:
/// the two folders, the state layout, where `prompt.md` and `.mcp.json` are, how
/// to reach the running kernel, and the main agents.
pub fn write_readme(h: &Host, state: &Path, work: &Path) -> Result<(), String> {
    let at = |bridge: &str, file: &str| {
        folder_of(h, bridge).map_or_else(|| format!("(the `{bridge}` agent is missing)"), |d| d.join(file).display().to_string())
    };
    let prompt = at(crate::kern::prompt::BRIDGE, crate::kern::prompt::FILE);
    let mcp = at(crate::kern::mcp_config::BRIDGE, crate::kern::mcp_config::FILE);
    let bin = std::env::current_exe().map_or_else(|_| "fantastic".to_string(), |p| p.display().to_string());
    let mut body = format!(
        "# This state folder belongs to a live AISixteen Fantastic kernel\n\n\
         Kept current: rewritten at every boot. Do not edit this file.\n\n\
         - state folder: `{state}`\n\
         - work folder: `{work}`\n\n\
         ## Layout\n\
         - `agent.yaml` — the root record\n\
         - `agents/` — every agent's folder and record\n\
         - `lock.yaml` — the pid of the kernel that holds this folder\n\
         - `cli/` — the local channel files\n\
         - `memory.db` — the kernel's memory\n\
         - `bundles/` — bundles written here\n\
         - `web/` — the page's files\n\n\
         ## Files\n\
         - `prompt.md`: `{prompt}` (every AI's system block)\n\
         - `.mcp.json`: `{mcp}` (the MCP config for a coding CLI)\n\n\
         ## Reach the running kernel\n\
         - `{bin} send --statedir {state} '<item json>'` — one call from a shell\n\
         - `{bin} mcp --statedir {state}` — the MCP server\n\
         - `claude --mcp-config {mcp}`\n",
        state = state.display(),
        work = work.display(),
    );
    for (title, parent) in [("The root's agents", h.root.as_str()), ("`user`'s agents", crate::env::HUMAN)] {
        body.push_str(&format!("\n## {title}\n"));
        for r in children_of(h, parent) {
            body.push_str(&r);
            body.push('\n');
        }
    }
    crate::atomic::write(&state.join("readme.md"), body.as_bytes())
}
