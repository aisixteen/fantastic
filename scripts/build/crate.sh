#!/bin/sh
# The `fantastic` crate for crates.io: ONE package holding the CLI and every
# crate it links, so a single `cargo install fantastic` builds it.
#
# The source tree keeps its separate crates; this script generates the package:
#
#   dist/crate/fantastic/
#     Cargo.toml        name `fantastic`; the union of every linked crate's deps
#     Cargo.lock        src/Cargo.lock (the versions the tree is tested with)
#     src/main.rs       each linked crate as a module: `#[path] mod fantastic_kernel;` …
#     src/<mirror>      each crate's src/ at its own path under src/, plus every
#                       file an include_str!/include_bytes! reaches outside it
#
# Inside the copies, `crate::` becomes `crate::<module>::` and `<crate>::` becomes
# `crate::<crate>::`. The canvas page is packed here (`pack.sh`) and embedded from
# the package, not from the build script, so the package builds without Go.
#
#   sh scripts/build/crate.sh             # generate + `cargo package` (builds it)
#   sh scripts/build/crate.sh --publish   # … then `cargo publish` (CARGO_REGISTRY_TOKEN)
#
# The version is the latest git tag unless FANTASTIC_VERSION names one.
#
# Needs jq.
set -eu

REPO="$(cd "$(dirname "$0")/../.." && pwd)"
SRC="$REPO/src"
PKG="$REPO/dist/crate/fantastic"
FEATURES="vllm,ollama,responses,anthropic"
PUBLISH=0
case "${1:-}" in
  --publish) PUBLISH=1 ;;
  "") ;;
  *) echo "usage: $(basename "$0") [--publish]" >&2; exit 2 ;;
esac
say() { echo "build/crate: $*"; }

# The release's version: the latest tag (v0.0.3 → 0.0.3), or FANTASTIC_VERSION.
VERSION="${FANTASTIC_VERSION:-$(git -C "$REPO" describe --tags --abbrev=0 | sed 's/^v//')}"
META=$(cd "$SRC" && cargo metadata --format-version 1 --manifest-path tui/Cargo.toml --features "$FEATURES")

rm -rf "$PKG"
mkdir -p "$PKG/src"

# ── the crates: <name> <dir relative to src/> ───────────────────────────────
CRATES=$(printf '%s\n' "$META" | jq -r --arg src "$SRC/" '.packages[] | select(.source == null)
  | "\(.name) \(.manifest_path | ltrimstr($src) | rtrimstr("/Cargo.toml"))"' | sort)

# ── copy each crate's src/ (test files stay out: they only build under cfg(test))
printf '%s\n' "$CRATES" | while read -r name dir; do
  mkdir -p "$PKG/src/$dir"
  ( cd "$SRC/$dir" && find src -type f ! -name 'tests.rs' ! -name 'tests_*.rs' ! -path '*/tests/*' \
      | while read -r f; do mkdir -p "$PKG/src/$dir/$(dirname "$f")"; cp "$f" "$PKG/src/$dir/$f"; done )
done

# ── every file an include reaches outside a crate's src/ ────────────────────
( cd "$PKG/src" && grep -rlE 'include_(str|bytes)!' --include='*.rs' . ) | while read -r f; do
  grep -vE '^[[:space:]]*//' "$PKG/src/$f" | grep -oE 'include_(str|bytes)!\("[^"]+"\)' | sed -E 's/.*\("([^"]+)"\)/\1/' | while read -r rel; do
    target="$(dirname "$f")/$rel"
    [ -e "$PKG/src/$target" ] && continue
    real="$(cd "$SRC/$(dirname "$target")" && pwd -P)/$(basename "$target")"
    [ -f "$real" ] || { echo "build/crate: $f includes $rel, not found" >&2; exit 1; }
    mkdir -p "$PKG/src/$(dirname "$target")"
    cp "$real" "$PKG/src/$target"
  done
done

# ── the canvas page, packed now and embedded from the package ───────────────
say "packing the canvas page"
sh "$SRC/tui/web/canvas/scripts/pack.sh" >/dev/null
PAGE="$PKG/src/tui/bundles/fantastic-canvas-page/src"
cp "$SRC/tui/web/canvas/dist/canvas.zip" "$PAGE/canvas.zip"
sed 's|include_bytes!(concat!(env!("OUT_DIR"), "/canvas.zip"))|include_bytes!("canvas.zip")|' "$PAGE/lib.rs" > "$PAGE/lib.rs.new"
mv "$PAGE/lib.rs.new" "$PAGE/lib.rs"
grep -q 'include_bytes!("canvas.zip")' "$PAGE/lib.rs" || { echo "build/crate: canvas-page embed not rewritten" >&2; exit 1; }

# ── paths: each crate is now a module of one crate ──────────────────────────
MODS=$(printf '%s\n' "$CRATES" | awk '{ m = $1; gsub("-", "_", m); if ($1 == "fantastic-tui") m = "tui"; print m, $2 }')
LIBS=$(printf '%s\n' "$MODS" | awk '$1 != "tui" { print $1 }')
EXTERN=""
for m in $LIBS; do EXTERN="$EXTERN s/(^|[^A-Za-z0-9_:\$])$m::/\\1crate::$m::/g;"; done
printf '%s\n' "$MODS" | while read -r m dir; do
  find "$PKG/src/$dir/src" -name '*.rs' | while read -r f; do
    sed -E "s/(^|[^A-Za-z0-9_:\$])crate::/\\1crate::$m::/g; $EXTERN" "$f" > "$f.new"
    mv "$f.new" "$f"
  done
done
# the shell's `main` becomes the module's, called from the package root
sed 's/^fn main() -> Result<()> {/pub(crate) fn main() -> Result<()> {/' "$PKG/src/tui/src/main.rs" > "$PKG/src/tui/src/main.rs.new"
mv "$PKG/src/tui/src/main.rs.new" "$PKG/src/tui/src/main.rs"
grep -q '^pub(crate) fn main' "$PKG/src/tui/src/main.rs" || { echo "build/crate: tui main not found" >&2; exit 1; }

# ── src/main.rs ─────────────────────────────────────────────────────────────
{
  echo '//! Aisixteen Fantastic — the `fantastic` CLI and the crates it links, one'
  echo '//! module each. Generated by scripts/build/crate.sh from the source tree at'
  echo '//! https://github.com/aisixteen/fantastic; edit the tree, not this package.'
  echo '#![allow(unused, unexpected_cfgs, clippy::all)]'
  echo
  printf '%s\n' "$MODS" | while read -r m dir; do
    entry=lib.rs; [ "$m" = tui ] && entry=main.rs
    echo "#[path = \"$dir/src/$entry\"]"
    echo "mod $m;"
  done
  echo
  echo 'fn main() -> anyhow::Result<()> {'
  echo '    tui::main()'
  echo '}'
} > "$PKG/src/main.rs"

# ── Cargo.toml ──────────────────────────────────────────────────────────────
DEPS_JQ='[.packages[] | select(.source == null) | .dependencies[] | select(.kind == null and .source != null)]
  | group_by([(.target // ""), .name])
  | map({target: (.[0].target // ""), name: .[0].name, req: (.[0].req | ltrimstr("^")),
          def: (map(.uses_default_features) | any), feats: (map(.features[]) | unique)})
  | group_by(.target)[]
  | (if .[0].target == "" then "\n[dependencies]" else "\n[target.'\''\(.[0].target)'\''.dependencies]" end),
    (.[] | "\(.name) = { version = \"\(.req)\"" + (if .def then "" else ", default-features = false" end)
          + (if (.feats | length) > 0 then ", features = [\(.feats | map("\"" + . + "\"") | join(", "))]" else "" end) + " }")'
{
  cat <<EOF
# Generated by scripts/build/crate.sh — edit the source tree, not this file.
[package]
name = "fantastic"
version = "$VERSION"
edition = "2021"
rust-version = "1.88"
license = "AGPL-3.0-or-later"
description = "Aisixteen Fantastic — a kernel of agents: the fantastic CLI with its in-process kernel, browser canvas and MCP face"
repository = "https://github.com/aisixteen/fantastic"
homepage = "https://aisixteen.com/fantastic/"
readme = "README.md"
keywords = ["agents", "ai", "llm", "mcp", "kernel"]
categories = ["command-line-utilities", "development-tools"]
autobins = false
autoexamples = false
autotests = false
autobenches = false

[[bin]]
name = "fantastic"
path = "src/main.rs"

[features]
default = [$(echo "$FEATURES" | sed 's/[^,]*/"&"/g; s/,/, /g')]
EOF
  for f in $(echo "$FEATURES" | tr , ' '); do echo "$f = []"; done
  printf '%s\n' "$META" | jq -r "$DEPS_JQ"
  cat <<EOF

[profile.release.build-override]
strip = "none"

[workspace]
EOF
} > "$PKG/Cargo.toml"

cp "$SRC/Cargo.lock" "$PKG/Cargo.lock"
cp "$REPO/README.md" "$REPO/LICENSE" "$PKG/"

say "generated $PKG"
cd "$PKG"
cargo package --allow-dirty
say "packaged $PKG/target/package/fantastic-$VERSION.crate"
if [ "$PUBLISH" = 1 ]; then
  : "${CARGO_REGISTRY_TOKEN:?--publish needs CARGO_REGISTRY_TOKEN}"
  cargo publish --allow-dirty --no-verify
  say "published fantastic $VERSION"
fi
